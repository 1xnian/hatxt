def translate(name: str, en: str) -> str | None:
    if name in T:
        return T[name]
    if name in IDENTICAL:
        return en
    return None


def main() -> int:
    rc = _process(SRC, DST, label="strings")
    rc2 = _process(SRC_CHANGELOG, DST_CHANGELOG, label="changelog")
    return rc or rc2


def _process(src_path: str, dst_path: str, label: str) -> int:
    src = open(src_path, encoding="utf-8").read()
    entries = re.findall(r'<string name="([^"]+)"([^>]*)>(.*?)</string>', src, re.S)

    body = []
    untranslated = []
    identical_passthrough = []

    for name, attrs, value in entries:
        if 'translatable="false"' in attrs:
            continue
        zh = translate(name, value)
        if zh is None:
            untranslated.append((name, value))
            continue
        if zh == value:
            identical_passthrough.append(name)
        attr_part = ' translatable="true"' if 'translatable=' in attrs else ""
        body.append(f'    <string name="{name}"{attr_part}>{zh}</string>')

    header = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!--\n"
        "    简体中文（中国大陆）翻译。\n"
        "\n"
        "    维护约定：\n"
        "      * 只翻译用户可见文案；协议名（TXT / SRV / DNS / WebSocket / TLS / Wi-Fi / NFC / IP）、\n"
        "        类名、日志标签以及服务器返回的自定义内容一律保留原文。\n"
        "      * 格式占位符（%1$s、%d、%1$d%% …）必须与 values/strings.xml 完全一致。\n"
        "      * 本文件由 tools/generate_zh_rCN.py 生成，请修改脚本词条后重新生成。\n"
        "-->\n"
        "<resources>\n"
    )
    with open(dst_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(header)
        fh.write("\n".join(body))
        fh.write("\n</resources>\n")

    print(f"[{label}] 写入 {dst_path}")
    print(f"[{label}]   已翻译      : {len(body)}")
    print(f"[{label}]   保留原文    : {len(identical_passthrough)}")
    print(f"[{label}]   仍未翻译    : {len(untranslated)}")
    if untranslated:
        with open(f"untranslated_{label}.txt", "w", encoding="utf-8") as fh:
            for name, value in untranslated:
                fh.write(f"{name}\t{value}\n")
        print(f"[{label}]   明细见 untranslated_{label}.txt")
    return 0


